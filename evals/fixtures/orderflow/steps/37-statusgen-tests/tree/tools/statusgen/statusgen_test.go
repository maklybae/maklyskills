package main

import (
	"strings"
	"testing"
)

func TestParseStatuses(t *testing.T) {
	statuses, err := parseStatuses("testdata/lifecycle.go")
	if err != nil {
		t.Fatalf("parseStatuses: %v", err)
	}

	want := []status{
		{Name: "draft", Code: 0},
		{Name: "in_transit", Code: 1},
		{Name: "done", Code: 2},
	}
	if len(statuses) != len(want) {
		t.Fatalf("parsed %d statuses (%v), want %d", len(statuses), statuses, len(want))
	}
	for i, got := range statuses {
		if got != want[i] {
			t.Errorf("status %d = %+v, want %+v", i, got, want[i])
		}
	}
}

func TestWireName(t *testing.T) {
	tests := []struct {
		constName string
		want      string
	}{
		{constName: "StatusPending", want: "pending"},
		{constName: "StatusPartiallyShipped", want: "partially_shipped"},
		{constName: "StatusOnHold", want: "on_hold"},
	}

	for _, tt := range tests {
		t.Run(tt.constName, func(t *testing.T) {
			if got := wireName(tt.constName); got != tt.want {
				t.Fatalf("wireName(%q) = %q, want %q", tt.constName, got, tt.want)
			}
		})
	}
}

func TestRenderIsFormattedAndStable(t *testing.T) {
	statuses := []status{{Name: "draft", Code: 0}, {Name: "done", Code: 1}}

	first, err := render(statuses)
	if err != nil {
		t.Fatalf("render: %v", err)
	}
	second, err := render(statuses)
	if err != nil {
		t.Fatalf("render again: %v", err)
	}

	if string(first) != string(second) {
		t.Fatal("two renders of the same input differ")
	}
	if !strings.HasPrefix(string(first), "// Code generated by make generate. DO NOT EDIT.\n") {
		t.Fatalf("generated file misses its banner, starts with %q", firstLine(string(first)))
	}
	if !strings.Contains(string(first), "\t0: \"draft\",\n\t1: \"done\",\n") {
		t.Fatalf("generated file misses the sorted name table:\n%s", first)
	}
}

func firstLine(s string) string {
	line, _, _ := strings.Cut(s, "\n")
	return line
}
