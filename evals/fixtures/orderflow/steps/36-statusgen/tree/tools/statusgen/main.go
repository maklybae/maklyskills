// Command statusgen turns the order lifecycle constants into the lookup tables
// the core package uses for wire names. Run it through `make generate`.
package main

import (
	"bytes"
	"flag"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/token"
	"log"
	"os"
	"slices"
	"strings"
	"unicode"

	"orderflow/pkg/xerrors"
)

// Only constants of this type, named with it as prefix, end up in the tables.
const statusType = "Status"

type status struct {
	Name string
	Code uint8
}

func main() {
	log.SetFlags(0)
	log.SetPrefix("statusgen: ")

	src := flag.String("src", "", "Go file declaring the status constants")
	out := flag.String("out", "", "file to write")
	flag.Parse()

	if *src == "" || *out == "" {
		log.Fatal("both -src and -out are required")
	}

	statuses, err := parseStatuses(*src)
	if err != nil {
		log.Fatal(err)
	}
	if len(statuses) == 0 {
		log.Fatalf("no %s constants found in %s", statusType, *src)
	}

	code, err := render(statuses)
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile(*out, code, 0o644); err != nil {
		log.Fatal(xerrors.Wrapf(err, "write %s", *out))
	}
}

func parseStatuses(path string) ([]status, error) {
	fileSet := token.NewFileSet()
	file, err := parser.ParseFile(fileSet, path, nil, parser.SkipObjectResolution)
	if err != nil {
		return nil, xerrors.Wrapf(err, "parse %s", path)
	}

	var statuses []status
	for _, decl := range file.Decls {
		genDecl, ok := decl.(*ast.GenDecl)
		if !ok || genDecl.Tok != token.CONST {
			continue
		}
		statuses = append(statuses, statusesInBlock(genDecl)...)
	}

	slices.SortFunc(statuses, func(a, b status) int { return int(a.Code) - int(b.Code) })
	return statuses, nil
}

// statusesInBlock walks one const block. Only its first spec carries the type
// and the iota expression; the rest inherit both, and their position in the
// block is their value.
func statusesInBlock(block *ast.GenDecl) []status {
	var (
		statuses []status
		typed    bool
	)
	for position, spec := range block.Specs {
		valueSpec, ok := spec.(*ast.ValueSpec)
		if !ok {
			continue
		}
		if valueSpec.Type != nil {
			ident, isIdent := valueSpec.Type.(*ast.Ident)
			typed = isIdent && ident.Name == statusType
		}
		if !typed || len(valueSpec.Names) != 1 {
			continue
		}

		name := valueSpec.Names[0].Name
		if name == statusType || !strings.HasPrefix(name, statusType) {
			continue
		}
		statuses = append(statuses, status{Name: wireName(name), Code: uint8(position)})
	}
	return statuses
}

func wireName(constName string) string {
	var name strings.Builder
	for i, r := range strings.TrimPrefix(constName, statusType) {
		if unicode.IsUpper(r) {
			if i > 0 {
				name.WriteByte('_')
			}
			r = unicode.ToLower(r)
		}
		name.WriteRune(r)
	}
	return name.String()
}

func render(statuses []status) ([]byte, error) {
	var buf bytes.Buffer
	buf.WriteString("// Code generated by make generate. DO NOT EDIT.\n\n")
	buf.WriteString("package generated\n\n")

	buf.WriteString("var statusNames = map[uint8]string{\n")
	for _, s := range statuses {
		fmt.Fprintf(&buf, "\t%d: %q,\n", s.Code, s.Name)
	}
	buf.WriteString("}\n\n")

	buf.WriteString("var statusCodes = map[string]uint8{\n")
	for _, s := range statuses {
		fmt.Fprintf(&buf, "\t%q: %d,\n", s.Name, s.Code)
	}
	buf.WriteString("}\n\n")

	buf.WriteString(`// StatusName returns the wire name of an order status code.
func StatusName(code uint8) (string, bool) {
	name, ok := statusNames[code]
	return name, ok
}

// StatusCode returns the order status behind a wire name.
func StatusCode(name string) (uint8, bool) {
	code, ok := statusCodes[name]
	return code, ok
}
`)

	formatted, err := format.Source(buf.Bytes())
	if err != nil {
		return nil, xerrors.Wrap(err, "format generated source")
	}
	return formatted, nil
}
